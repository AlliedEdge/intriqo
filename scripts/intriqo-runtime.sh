}

intriqo_wait_for_postgres() {
    local timeout=${1:-60} elapsed=0
    local host=${INTRIQO_POSTGRES_HOST:-127.0.0.1}
    local port=${INTRIQO_POSTGRES_PORT:-5432}
    local user=${POSTGRES_USER:-intriqo}
    local database=${POSTGRES_DB:-intriqo}
    while ! pg_isready -q -h "$host" -p "$port" -U "$user" -d "$database"; do
        (( elapsed >= timeout )) && { intriqo_die "PostgreSQL was not ready within ${timeout}s"; return 1; }
        sleep 1
        elapsed=$((elapsed + 1))
    done
}

intriqo_health_ok() {
    local url=${1:-http://${INTRIQO_API_HOST:-127.0.0.1}:${INTRIQO_API_PORT:-8000}/ready}
    local body
    body=$(curl --fail --silent --show-error --max-time 3 "$url" 2>/dev/null) || return 1
    "$INTRIQO_PYTHON" -c 'import json,sys; value=json.load(sys.stdin); raise SystemExit(0 if value.get("status") in {"ok", "ready"} else 1)' <<< "$body"
}

intriqo_wait_for_health() {
    local timeout=${1:-60} elapsed=0
    local url=${2:-http://${INTRIQO_API_HOST:-127.0.0.1}:${INTRIQO_API_PORT:-8000}/ready}
    while ! intriqo_health_ok "$url"; do
        (( elapsed >= timeout )) && { intriqo_die "Control Plane HTTP readiness failed at $url"; return 1; }
        sleep 1
        elapsed=$((elapsed + 1))
    done
}

intriqo_wait_for_engine_ready() {
    local service_pid=$1 log_file=$2 timeout=${3:-60} elapsed=0
    while :; do
        grep -q 'capture_ready=true' "$log_file" 2>/dev/null && return 0
        # Synthetic and PCAP captures are finite; a complete shutdown is a
        # valid readiness result when it happened after engine startup.
        grep -q 'shutdown status=complete' "$log_file" 2>/dev/null && return 0
        if ! intriqo_pid_running "$service_pid"; then
            intriqo_die "IDS engine exited before becoming ready; see $log_file"
            return 1
        fi
        (( elapsed >= timeout )) && { intriqo_die "IDS engine readiness failed; see $log_file"; return 1; }
        sleep 1
        elapsed=$((elapsed + 1))
    done
}

intriqo_wait_for_ml_ready() {
    local status_file=$1 timeout=${2:-60} elapsed=0 state
    while :; do
        if [[ -f "$status_file" ]]; then
            state=$(
                "$INTRIQO_PYTHON" - "$status_file" <<'PY'
import json
import sys

try:
    with open(sys.argv[1], encoding="utf-8") as stream:
        print(json.load(stream).get("state", ""))
except (OSError, ValueError):
    print("")
PY
            )
            case "$state" in
                READY) return 0 ;;
                FAILED|DEGRADED|DISABLED)
                    intriqo_die "ML worker entered $state; see $INTRIQO_LOG_DIR/ml-worker.log"
                    return 1
                    ;;
            esac
        fi
        if ! intriqo_service_running ml-worker; then
            intriqo_die "ML worker exited before becoming READY; see $INTRIQO_LOG_DIR/ml-worker.log"
            return 1
        fi
        (( elapsed >= timeout )) && { intriqo_die "ML worker readiness failed; see $INTRIQO_LOG_DIR/ml-worker.log"; return 1; }
        sleep 1
        elapsed=$((elapsed + 1))
    done
}

intriqo_choose_python() {
    if [[ -n "${INTRIQO_PYTHON:-}" ]]; then
        printf '%s\n' "$INTRIQO_PYTHON"
    elif [[ -x "$INTRIQO_ROOT_DIR/.venv/bin/python" ]]; then
        printf '%s\n' "$INTRIQO_ROOT_DIR/.venv/bin/python"
    elif [[ -x "$INTRIQO_ROOT_DIR/control-plane/.venv/bin/python" ]]; then
        printf '%s\n' "$INTRIQO_ROOT_DIR/control-plane/.venv/bin/python"
    else
        command -v python3 || command -v python
    fi
}

